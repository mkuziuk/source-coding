def choose_component(source, rng):
    # компонента смеси выбирается один раз на всю реализацию
    while source.kind == "mixture":
        name = rng.choices(list(source.weights), weights=list(source.weights.values()))[0]
        source = source.components[name]
    return source


def markov_next(source, previous):
    # распределение следующего символа при предыдущих символах previous
    if len(previous) == source.memory:
        return source.models[source.transitions[tuple(previous)]]

    # первые d символов берутся из initial при уже выданном начале
    n = len(previous)
    weights = {}
    for context, p in source.initial.items():
        if list(context[:n]) == previous:
            weights[context[n]] = weights.get(context[n], 0) + p
    return weights


def generate(source: Source, i, previous, rng: Random):
    if source.kind == "markov":
        model = markov_next(source, previous)
    else:
        switch = source.switches[source.source[i % source.L]]
        model_name = rng.choices(list(switch), weights=list(switch.values()))[0]
        model = source.models[model_name]

    return rng.choices(list(model), weights=list(model.values()))[0]


def mode_1(source, N, rng):
    source = choose_component(source, rng)

    # при N <= 0 или None выдача бесконечная, остановка - Ctrl + C
    infinite = N is None or N <= 0
    i = 0
    previous = []  # последние source.memory символов
    try:
        while infinite or i < N:
            symbol = generate(source, i, previous, rng)
            print(symbol, end=" ")
            previous.append(symbol)
            if len(previous) > source.memory:
                previous.pop(0)
            i += 1
    except KeyboardInterrupt:
        pass
    print()


def symbol_probability(source, i, symbol):
    switch = source.switches[source.source[i % source.L]]
    return sum(p * source.models[model].get(symbol, 0) for model, p in switch.items())


def context_distribution(source, steps):
    # распределение d символов, начиная с такта steps
    distribution = dict(source.initial)
    for _ in range(steps):
        new_distribution = {}
        for context, p in distribution.items():
            for symbol, q in source.models[source.transitions[context]].items():
                new_context = context[1:] + (symbol,)
                new_distribution[new_context] = new_distribution.get(new_context, 0) + p * q
        distribution = new_distribution
    return distribution


def markov_probability(source, start, sequence):
    d = source.memory
    head = tuple(sequence[:d])
    result = sum((p for context, p in context_distribution(source, start).items()
                  if context[:len(head)] == head), Fraction(0))

    context = head
    for symbol in sequence[d:]:
        if result == 0:
            break
        result *= source.models[source.transitions[context]].get(symbol, 0)
        context = context[1:] + (symbol,)
    return result


def sequence_probability(source, start, sequence):
    if source.kind == "mixture":
        return sum(weight * sequence_probability(source.components[name], start, sequence)
                   for name, weight in source.weights.items())
    if source.kind == "markov":
        return markov_probability(source, start, sequence)

    result = Fraction(1)
    for t, symbol in enumerate(sequence):
        result *= symbol_probability(source, start + t, symbol)
    return result


def frequency(source, N, sequence, rng):
    source = choose_component(source, rng)
    realization = []
    for i in range(N):
        previous = realization[max(0, i - source.memory):]
        realization.append(generate(source, i, previous, rng))

    r = len(sequence)
    hits = sum(realization[i:i + r] == sequence for i in range(N - r + 1))
    return Fraction(hits, N - r + 1)


def mode_2(source, N, sequence, rng):
    first = sequence_probability(source, 0, sequence)
    average = sum(sequence_probability(source, j, sequence) for j in range(source.L)) / source.L

    print(f"Точная вероятность с первого такта: {first} ~ {float(first):.6g}")
    print(f"Среднее по позициям периода: {average} ~ {float(average):.6g}")
    print(f"Частотная оценка при N = {N}: {float(frequency(source, N, sequence, rng)):.6g}")

    print()
    print("N", "оценка", "|- первый|", "|- среднее|")
    for n in [10**2, 10**3, 10**4, 10**5, 10**6]:
        if n < len(sequence):
            continue
        f = frequency(source, n, sequence, rng)
        print(n, float(f), float(abs(f - first)), float(abs(f - average)))


def main():
    # generated by claude start
    parser = argparse.ArgumentParser()
    parser.add_argument("source")
    parser.add_argument("N")
    parser.add_argument("sequence", nargs="*", help="символы a1 ... ar для режима 2")
    parser.add_argument("--mode", type=int, choices=[1, 2], default=1)
    parser.add_argument("--seed", type=int)
    args = parser.parse_args()

    try:
        with open(args.source, encoding="utf-8") as file:
            source = Source(json.load(file))
        N = None if args.N == "None" else int(args.N)
        if args.mode == 2 and not (args.sequence and N is not None and N >= len(args.sequence)):
            raise ValueError("в режиме 2 нужны непустая последовательность и N не меньше её длины")
    except (OSError, ValueError) as error:
        print(f"Ошибка: {error}")
        sys.exit(1)

    # end

    rng = Random(args.seed)
    try:
        if args.mode == 1:
            mode_1(source, N, rng)
        else:
            mode_2(source, N, args.sequence, rng)
    except KeyboardInterrupt:
        print()
        print("Прервано пользователем")
        sys.exit(1)


if __name__ == "__main__":
    main()
