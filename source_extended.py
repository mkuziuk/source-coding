import argparse
import json
import sys
from fractions import Fraction
from itertools import product
from math import lcm
from random import Random


class Source:
    def __init__(self, source_description):
        if not isinstance(source_description, dict):
            raise ValueError("Описание источника должно быть объектом JSON")

        if "mixture" in source_description:
            self.kind = "mixture"
            self.parse_mixture(source_description["mixture"])
        elif "memory" in source_description:
            self.kind = "markov"
            self.parse_markov(source_description)
        else:
            self.kind = "basic"
            self.parse_basic(source_description)

    # generated by claude
    def parse_basic(self, source_description):
        self.models = parse_section(source_description, "models")
        self.switches = parse_section(source_description, "switches")
        self.source = source_description.get("source")

        for name, distribution in self.switches.items():
            unknown_models = distribution.keys() - self.models.keys()
            if unknown_models:
                raise ValueError(f"switches.{name}: неизвестные модели {sorted(unknown_models)}")

        if not isinstance(self.source, list) or not self.source:
            raise ValueError("source должен быть непустым списком переключателей")
        for name in self.source:
            if not isinstance(name, str) or name not in self.switches:
                raise ValueError(f"source: неизвестный переключатель {name}")

        self.L = len(self.source)
        self.memory = 0

    def parse_markov(self, source_description):
        self.memory = source_description["memory"]
        if type(self.memory) is not int or self.memory < 1:
            raise ValueError("memory: нужно целое число не меньше 1")
        d = self.memory

        self.models = parse_section(source_description, "models")
        self.alphabet = sorted({symbol for model in self.models.values() for symbol in model})

        initial = parse_distribution("initial", source_description.get("initial"))
        self.initial = {parse_context("initial", text, d, self.alphabet): p
                        for text, p in initial.items()}

        transitions = source_description.get("transitions")
        if not isinstance(transitions, dict):
            raise ValueError("transitions: нужен объект")
        self.transitions = {}
        for text, model in transitions.items():
            if not isinstance(model, str) or model not in self.models:
                raise ValueError(f"transitions: неизвестная модель {model}")
            self.transitions[parse_context("transitions", text, d, self.alphabet)] = model

        for context in product(self.alphabet, repeat=d):
            if context not in self.transitions:
                raise ValueError(f"transitions: нет модели для контекста '{' '.join(context)}'")

        self.L = 1

    def parse_mixture(self, mixture):
        if not isinstance(mixture, dict) or not mixture:
            raise ValueError("mixture: нужен непустой объект")

        self.components = {}
        probabilities = {}
        for name, component in mixture.items():
            if not isinstance(component, dict):
                raise ValueError(f"mixture.{name}: нужен объект")
            probabilities[name] = component.get("probability")
            description = {key: value for key, value in component.items() if key != "probability"}
            try:
                self.components[name] = Source(description)
            except ValueError as error:
                raise ValueError(f"mixture.{name}: {error}")

        self.weights = parse_distribution("mixture", probabilities)
        self.L = lcm(*(component.L for component in self.components.values()))
        self.memory = 0


def parse_section(source_description, section_name):
    section = source_description.get(section_name)
    if not isinstance(section, dict) or not section:
        raise ValueError(f"{section_name}: нужен непустой объект")

    return {name: parse_distribution(f"{section_name}.{name}", distribution)
            for name, distribution in section.items()}


def parse_distribution(location, distribution):
    if not isinstance(distribution, dict) or not distribution:
        raise ValueError(f"{location}: нужно непустое распределение")
    if not all(isinstance(p, str) for p in distribution.values()):
        raise ValueError(f"{location}: вероятности должны быть строками")

    try:
        probabilities = {item: Fraction(p) for item, p in distribution.items()}
    except (ValueError, ZeroDivisionError) as error:
        raise ValueError(f"{location}: некорректная вероятность") from error

    if any(p < 0 for p in probabilities.values()):
        raise ValueError(f"{location}: отрицательная вероятность")
    if sum(probabilities.values()) != 1:
        raise ValueError(f"{location}: сумма вероятностей должна быть равна 1")

    return probabilities


def parse_context(location, text, d, alphabet):
    # контекст записывается как d символов через пробел, например "0 1"
    context = tuple(text.split())
    if len(context) != d or not all(symbol in alphabet for symbol in context):
        raise ValueError(f"{location}: контекст '{text}' должен состоять из {d} символов алфавита")
    return context

